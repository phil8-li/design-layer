#!/usr/bin/env node
/**
 * Vendors Sonner's stylesheet into `src/core/css/sonner-css.ts`.
 *
 *   node tools/build-sonner-css.mjs          # rewrite the module
 *   node tools/build-sonner-css.mjs --check  # fail if it is out of date
 *
 * WHY IT IS COPIED RATHER THAN IMPORTED
 *
 * `import sonnerCss from "sonner/dist/styles.css"` is the obvious spelling, and
 * `build.mjs` can be taught esbuild's `text` loader in one line. Every OTHER
 * build in this repo cannot. Each jsdom suite in `test/` compiles the lane it
 * is testing with its own `esbuild` call from `stdin`, with `write: false` and
 * no output path — and esbuild refuses a CSS import in that mode outright:
 *
 *   Cannot import "node_modules/sonner/dist/styles.css" into a JavaScript file
 *   without an output path configured
 *
 * `core/bridge.ts` reaches the toast, so the stylesheet lands in the import
 * graph of essentially every suite in the package. Teaching forty harnesses a
 * loader to serve one import is the wrong end to fix it from; a `.ts` module
 * exporting a string is importable by all of them and by nothing else.
 *
 * It stays honest the way `src/core/icons.ts` does — generated, checked in, and
 * re-checked by `npm run verify`, so a `sonner` bump that changes the
 * stylesheet fails the build instead of silently shipping last version's CSS
 * against this version's markup.
 */

import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"

const require = createRequire(import.meta.url)
const root = path.dirname(fileURLToPath(new URL("../package.json", import.meta.url)))
const OUT = path.join(root, "src", "core", "css", "sonner-css.ts")

const SOURCE = require.resolve("sonner/dist/styles.css")
// Read rather than required: sonner's `exports` map does not list its own
// `package.json`, so the resolver refuses the specifier. The manifest sits
// beside `dist/`, and that is a fact about npm layout rather than about sonner.
const manifest = path.join(path.dirname(path.dirname(SOURCE)), "package.json")
const { version } = JSON.parse(fs.readFileSync(manifest, "utf8"))
const css = fs.readFileSync(SOURCE, "utf8")

/*
 * A template literal rather than `JSON.stringify`, so the generated file diffs
 * line by line when the library's CSS changes. Sonner's stylesheet contains no
 * backtick, backslash or `${` today; escaping them anyway is what keeps that
 * from becoming a silent syntax error the day it does.
 */
const literal = css.replace(/[\\`]/g, "\\$&").replace(/\$\{/g, "\\${")

const file = `/**
 * Sonner ${version}'s \`dist/styles.css\`, verbatim.
 *
 * GENERATED by \`node tools/build-sonner-css.mjs\` — do not edit. The editor's
 * own overrides live next door in \`css/toast.ts\`, which is where a change to
 * how a toast LOOKS belongs; this file is the library's, and every byte of it
 * should stay the library's so a version bump is a clean re-run.
 *
 * Copied rather than imported because every jsdom suite in \`test/\` bundles its
 * lane with esbuild and no output path, where a \`.css\` import is a hard error.
 * The tool's header has the long version.
 */

export const sonnerCss = \`${literal}\`
`

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : ""
  if (current !== file) {
    console.error("STALE src/core/css/sonner-css.ts — run `node tools/build-sonner-css.mjs`")
    process.exit(1)
  }
  console.log(`PASS src/core/css/sonner-css.ts matches sonner ${version} (${css.length} bytes)`)
  process.exit(0)
}

fs.writeFileSync(OUT, file)
console.log(
  `Wrote ${path.relative(root, OUT)} — ${css.length} bytes of CSS from sonner ${version}`
)
